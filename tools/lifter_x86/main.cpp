// recomp_lift: lifts a 32-bit x86 PE (the game EXE) to C++.
//
//   recomp_lift --exe <game.exe> --symbols symbols --out generated
//            [--manifest lifter.manifest] [--insns-per-file N] [--dump VA]
//            [--x87-test OUT.cpp]   (forms for tests/x86/lift_x87_test.cpp)
//            [--int-test OUT.cpp]   (forms for tests/x86/lift_int_test.cpp)
//            [--sse-test OUT.cpp]   (forms for tests/x86/lift_sse_test.cpp)
//            [--module <game.dll> --symbols DIR [--manifest FILE]
//             [--base HEX]]...
//            [--only VA[,VA...]]   (just these functions and their callees)
//            [--sweep-gaps]   (also lift .text code nothing refers to)
//            [--dump-discovery]   (final_jumptables/entries, lifted_insns.txt)
//   recomp_lift (--forms LIST | --code BIN) [--x64]
//               (--x87-test | --int-test | --sse-test) OUT.cpp
//
// Each --module adds a DLL the game loads itself, lifted into the same
// output; --symbols/--manifest/--base after it apply to that DLL. DLLs
// load at their preferred base unless --base moves them (needed only when
// two modules overlap; the game's GameConfig must then give the same
// base). Their functions go into gen_<module>_NNN.cpp, the EXE's into
// gen_NNN.cpp, and table.cpp lists them all.
//
// --exe and --module also take the formats an enabled platform module
// reads (ARCHITECTURE.md, "Layout: base, CPU cores, platform modules");
// for those, --symbols "" lifts without Ghidra's symbols.
//
// --forms takes the instruction forms from LIST (hex encodings, see
// WriteFormListTest) instead of an image, --code from flat machine code;
// --x64 decodes them as 64-bit code.
//
// --only lifts the given functions and whatever they call or tail-call
// directly, nothing else (no Ghidra entries, exports or pointer
// discovery): for oracle tests that run a few original routines lifted.
//
// Pass 1 discovers functions to a fixpoint (Ghidra entries + exports +
// every direct call/tail-call target and setjmp return point found while
// descending). Pass 2 rebuilds every function against the final entry
// set, so jumps to code that turned out to be an entry become tail calls
// consistently. Then the functions are emitted into generated/gen_NNN.cpp
// plus a table file.

